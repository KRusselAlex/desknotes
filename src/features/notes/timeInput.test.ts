import { parseTime } from "./timeInput";

describe("parseTime", () => {
  it.each([
    ["14:00", "14:00"],
    ["9:30", "09:30"],
    ["09:30", "09:30"],
    ["930", "09:30"],
    ["0930", "09:30"],
    ["2130", "21:30"],
    ["9", "09:00"],
    ["21", "21:00"],
    ["0", "00:00"],
    ["9.30", "09:30"],
    ["9h30", "09:30"],
    ["9 30", "09:30"],
    [" 9:05 ", "09:05"],
  ])("reads %j as %s", (typed, time) => {
    expect(parseTime(typed)).toBe(time);
  });

  it.each([
    ["9pm", "21:00"],
    ["9 PM", "21:00"],
    ["9:30 pm", "21:30"],
    ["9.30p", "21:30"],
    ["930pm", "21:30"],
    ["12am", "00:00"],
    ["12:30 AM", "00:30"],
    ["12pm", "12:00"],
    ["12:15 p.m.", "12:15"],
    ["7 a.m.", "07:00"],
  ])("reads the 12-hour %j as %s", (typed, time) => {
    expect(parseTime(typed)).toBe(time);
  });

  it.each(["", "  ", "24:00", "9:60", "25", "13pm", "0am", "abc", "9:3", "12345", "9::30", "-1", "9:30 xm"])(
    "refuses %j",
    (typed) => {
      expect(parseTime(typed)).toBeNull();
    },
  );
});
